// OPT-IN: needs the live stack. Start the service with scripts/run_c1_live.ps1 (writing model + model c1-req), then in project/apps/web:
//   $env:C1_E2E_LIVE = "1"; npm run e2e
// Paths are relative to project/apps/web (where npm run e2e runs).
import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const SRS = resolve(process.cwd(), '../../../scripts/fixtures/live_check_srs.txt')
const SHOTS = resolve(process.cwd(), '../../outputs/c1_live_check')

test.skip(process.env.C1_E2E_LIVE !== '1', 'opt-in live test: set C1_E2E_LIVE=1 with the live service on :8000 (scripts/run_c1_live.ps1) and the writing model running')

test('live stack: add a document, run the analysis, a real draft appears in the Review Queue', async ({ page, request }) => {
  test.setTimeout(15 * 60_000)
  const health = await (await request.get('http://127.0.0.1:8000/api/health')).json()
  expect(health.generation_backend, 'start the service with scripts/run_c1_live.ps1').toBe('ollama')
  expect(health.generation_reachable, 'the writing model c1-req must be reachable').toBe(true)
  expect(health.generation_target, 'this test expects the device target: switch to On device first').toBe('device')

  await page.goto('/requirement/sources')
  await page.getByTestId('upload-button').click()
  await page.getByTestId('file-input').setInputFiles(SRS)
  await page.getByTestId('upload-submit').click()
  await expect(page.getByTestId('sources-card')).toContainText('live_check_srs.txt')

  await page.getByTestId('analyse-pending').click()
  await expect(page.getByRole('button', { name: /Analysing/ })).toBeDisabled()
  await expect(page.getByTestId('analysis-badge')).not.toContainText('Analysing', { timeout: 5 * 60_000 })

  // wait until at least one requirement has a draft written by the live model (tens of seconds per draft on a 4 GB GPU)
  await page.getByRole('link', { name: 'Review Queue' }).click() // the drafts are read in the Review Queue now
  const prov = page.getByTestId('provenance').first()
  // the default "smart" policy writes drafts for P1 requirements only: open rows until one has a finished draft
  await expect(async () => {
    const rows = page.getByTestId('finding-row')
    let found = false
    for (let i = 0; i < (await rows.count()) && !found; i++) {
      await rows.nth(i).click()
      found = (await page.getByTestId('provenance').count()) > 0
    }
    expect(found).toBe(true)
  }).toPass({ timeout: 10 * 60_000, intervals: [5_000] })
  await expect(prov).toContainText('Generated by AI · on device')
  await expect(prov).not.toContainText('c1-req') // the model name belongs in Processing details only

  mkdirSync(SHOTS, { recursive: true })
  await page.screenshot({ path: resolve(SHOTS, 'live_draft.png'), fullPage: true })

  // tidy up: remove only the file this test added
  await page.getByRole('link', { name: 'Sources & Findings' }).click()
  await page.getByRole('button', { name: 'Remove live_check_srs.txt' }).click()
  await page.getByRole('dialog', { name: /Remove live_check_srs.txt/ }).getByRole('button', { name: 'Remove' }).click()
  await expect(page.getByTestId('sources-card')).not.toContainText('live_check_srs.txt')
})
