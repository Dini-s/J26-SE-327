from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
INPUT = ROOT / "data" / "processed" / "hrim_semantic_fused_features.csv"
OUTPUT = ROOT / "data" / "processed" / "hrim_feature_availability.csv"

KEYS = ["repository", "package_path"]


def main():
    df = pd.read_csv(INPUT)

    semantic_cols = [
        c for c in df.columns if c.startswith("semantic_emb_")
    ]
    graph_cols = [
        "graph_in_degree",
        "graph_out_degree",
        "graph_total_degree",
        "graph_pagerank",
        "graph_betweenness",
    ]
    evolution_cols = [
        "commit_count",
        "contributor_count",
        "files_changed",
        "total_insertions",
        "total_deletions",
        "total_churn",
    ]

    if df.duplicated(KEYS).any():
        raise ValueError("Duplicate repository/package keys found.")

    report = df[KEYS].copy()
    report["semantic_available"] = df[semantic_cols].notna().all(axis=1)
    report["graph_available"] = df[graph_cols].notna().all(axis=1)
    report["evolution_available"] = df[evolution_cols].notna().all(axis=1)

    report["available_feature_groups"] = report[
        ["semantic_available", "graph_available", "evolution_available"]
    ].sum(axis=1)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    report.to_csv(OUTPUT, index=False)

    print("Packages audited:", len(report))
    print("\nFeature-group availability:")
    for column in [
        "semantic_available",
        "graph_available",
        "evolution_available",
    ]:
        print(f"{column}: {int(report[column].sum())}/{len(report)}")

    print("\nAvailability combinations:")
    print(
        report.groupby(
            ["semantic_available", "graph_available", "evolution_available"],
            dropna=False,
        ).size().to_string()
    )

    print(f"\nSaved: {OUTPUT}")
    print("No labels were generated by this script.")


if __name__ == "__main__":
    main()
