"""Part B jobs for the API: a dispatcher thread takes requirements from a priority queue and hands them to a small worker pool that calls the existing generation module.

Per-requirement state: not_requested | queued | running | done | needs_clarification | failed | manual_review.
    done / needs_clarification   a valid reply (cached by sha256(requirement text + backend kind + model name))
    manual_review                the model replied but all 3 attempts were invalid (the last raw reply is kept; not cached)
    failed                       no reply at all: the model server is unreachable, or the text is not in the replay file (nothing is made up)
A single requirement can be re-run at once with priority over the queue (`run_now`), which skips the cache.

Policy (chosen per analysis run, see priority.py): smart = queue P1 only, all = queue everything ordered P1, P2, P3, manual = queue nothing. Requirements
that are not queued stay "not_requested" (shown as "not generated yet") until the user asks. A cached reply is applied at once, whatever the policy.
The queue lives in memory but every queued/running requirement is also a row in `generation` with its priority, so a restart re-queues them
(`resume_pending`). Pause stops the dispatcher from taking NEW items (items in flight finish); the flag and its reason are saved in sqlite.

Targets (engine.py): every item runs on the target that is active WHEN THE ITEM IS PICKED. "device" is the API's own Ollama model with one item in flight;
"cloud" is a remote OpenAI-compatible server with the configured number of items in flight (1 to 8). The dispatcher only admits a new item while
in_flight < the active target's concurrency, so priority order holds and switching takes effect for the next item. A cache key (text + backend kind + model)
is generated by one worker at a time, so duplicates wait for the first reply and then take it from the cache. Nothing ever falls back from cloud to device.
After 3 connection failures in a row on the cloud target the queue pauses itself (paused_reason "cloud_unreachable"); the user resumes or switches target.

The ETA is wall-clock throughput over the last 10 completions of the active target (since the last target switch) times the items waiting; hidden until 3.
"""
import hashlib
import json
import queue
import threading
import time

from .. import config as agent_config
from .. import generation as gen
from ..generation import BackendError, MockBackend, OllamaBackend, ReplayBackend, ReplayMiss
from . import priority, settings
from .db import dumps, loads, now
from .engine import CLOUD, DEVICE, POOL_SIZE, EngineStore, Target

STATES = ("not_requested", "queued", "running", "done", "needs_clarification", "failed", "manual_review")
NOT_IN_REPLAY = "not in replay file"
ENGINE_UNAVAILABLE = "AI engine unavailable"  # the UI shows its "engine unavailable" state when a failed draft's message starts with this
MAX_FAST_FAILS = 3  # device: after this many connection failures in a row the rest of the queue fails fast
CLOUD_FAIL_LIMIT = 3  # cloud: after this many connection failures in a row the queue pauses itself
CLOUD_UNREACHABLE = "cloud_unreachable"
ETA_WINDOW = 10
ETA_MIN_SAMPLES = 3
ORIGINAL, CLARIFIED = "original", "clarified"


def failure_reason(message):
    """A short code for why a draft failed, from the stored message: never the message itself (it can name a host or an error text). Codes:
    engine_unavailable | engine_skipped | cloud_unreachable | cloud_rejected | not_in_replay | engine_not_ready | unexpected | unknown."""
    m = message or ""
    if m.startswith(ENGINE_UNAVAILABLE):
        if "Cloud rejected" in m:
            return "cloud_rejected"
        if "Cloud unreachable" in m:
            return "cloud_unreachable"
        if "skipped after repeated failures" in m:
            return "engine_skipped"
        return "engine_unavailable"
    if m == NOT_IN_REPLAY:
        return "not_in_replay"
    if m.startswith("unexpected error"):
        return "unexpected"
    return "engine_not_ready" if m else "unknown"


def _norm(text):
    return " ".join(str(text or "").split())


def mock_reply(system, user):
    """Deterministic, clearly artificial reply for tests and demos (C1_GENERATION_BACKEND=mock). Not model output."""
    text = user[len(gen.USER_PREFIX):] if user.startswith(gen.USER_PREFIX) else user
    short = text.rstrip(".").strip()
    return json.dumps({
        "status": "ok",
        "user_story": f"As a user, I want {short[:1].lower() + short[1:]}, so that the requirement is met.",
        "technical_task": f"Implement and verify: {short}.",
        "acceptance_criteria": [f"Given the system is running, when the requirement is exercised, then the stated behaviour is met.",
                                f"Given invalid input, when the requirement is exercised, then the system reports an error."],
        "rationale": "MOCK output for testing; not produced by a language model.",
    })


def make_backend(name, replay_file=None):
    if name == "replay":
        return ReplayBackend(settings.replay_file(replay_file)), "replay"
    if name == "ollama":
        s = agent_config.llm_settings()
        return OllamaBackend(s), s["model"] or "(LLM_MODEL not set)"
    if name == "mock":
        return MockBackend(mock_reply), "mock"
    raise ValueError(f"unknown backend {name!r}")


def cache_key(text, backend_name, model_name):
    return hashlib.sha256("\n".join([text, backend_name, model_name]).encode("utf-8")).hexdigest()


class GenerationManager:
    def __init__(self, db, backend, backend_name, model_name, init_error=None, engine=None):
        self.db, self.backend, self.backend_name, self.model_name = db, backend, backend_name, model_name
        self.engine = engine or EngineStore(db, backend_name, model_name, backend)
        self.on_draft = None  # called with the uid when a draft was written or replaced (the auto-sync listens)
        self.init_error = init_error  # for example "replay file not found"; every job then fails with this message
        self.queue = queue.PriorityQueue()
        self._work = queue.Queue()  # items handed to the pool; never longer than the free slots
        self._seq = 0
        self._ticket = {}
        self._lock = threading.Lock()
        self._fails = 0  # device connection failures in a row
        self._cloud_fails = 0  # cloud connection failures in a row
        self._cv = threading.Condition()
        self._in_flight = 0
        self._key_locks = {}
        self._key_guard = threading.Lock()
        self._stop = threading.Event()
        self._paused = threading.Event()
        self._paused_reason = None
        if (self.db.one("SELECT value FROM settings WHERE key='gen_paused'") or {}).get("value") == "1":
            self._paused.set()
            self._paused_reason = (self.db.one("SELECT value FROM settings WHERE key='gen_paused_reason'") or {}).get("value") or None
        self._dispatcher = threading.Thread(target=self._dispatch, name="c1-generation-dispatcher", daemon=True)
        self._pool = [threading.Thread(target=self._worker, name=f"c1-generation-worker-{i}", daemon=True) for i in range(POOL_SIZE)]

    # ------------------------------------------------------------------------------------------------ lifecycle
    def start(self):
        if not self._dispatcher.is_alive():
            self._dispatcher.start()
            for t in self._pool:
                t.start()

    def stop(self):
        self._stop.set()
        with self._cv:
            self._cv.notify_all()
        self.queue.put((99, 0, "", 0))  # wake the dispatcher
        if self._dispatcher.is_alive():
            self._dispatcher.join(timeout=5)
        for _ in self._pool:
            self._work.put(None)
        deadline = time.monotonic() + 5
        for t in self._pool:
            if t.is_alive():
                t.join(timeout=max(0.0, deadline - time.monotonic()))  # a worker stuck in a long request is a daemon thread: it does not keep the process alive

    def wait_idle(self, timeout=60.0):
        end = time.time() + timeout
        while self.queue.unfinished_tasks and time.time() < end:
            time.sleep(0.02)
        return self.queue.unfinished_tasks == 0

    # ------------------------------------------------------------------------------------------------ state
    def _set(self, uid, state, message="", result=None, attempts=0, manual_review=False, key=None):
        self.db.run(
            "INSERT INTO generation (uid, state, message, result, attempts, manual_review, cache_key, updated_at) VALUES (?,?,?,?,?,?,?,?) "
            "ON CONFLICT(uid) DO UPDATE SET state=excluded.state, message=excluded.message, result=excluded.result, attempts=excluded.attempts, "
            "manual_review=excluded.manual_review, cache_key=excluded.cache_key, updated_at=excluded.updated_at",
            (uid, state, message, dumps(result) if result is not None else None, attempts, int(manual_review), key, now()))
        if self.on_draft is not None and state in ("done", "needs_clarification", "manual_review"):
            try:
                self.on_draft(uid)
            except Exception:  # noqa: BLE001 - a listener never breaks the queue
                pass

    def enqueue(self, items):
        """items = [(uid, priority class 1-3)]; lower classes are taken first, then first come first served."""
        for uid, cls in items:
            with self._lock:
                self._seq += 1
                ticket = self._seq
                self._ticket[uid] = ticket
            self._set(uid, "queued")
            self.db.run("UPDATE generation SET priority=? WHERE uid=?", (cls, uid))
            self.queue.put((cls, ticket, uid, ticket))

    def source_text(self, uid):
        """(text to generate from, "original" | "clarified"). A decision "edited" with a really different text is the user's clarified text."""
        row = self.db.one("SELECT r.text, d.decision, d.edited_text FROM requirements r LEFT JOIN decisions d ON d.uid=r.uid WHERE r.uid=?", (uid,))
        if not row:
            return None, ORIGINAL
        edited = (row["edited_text"] or "").strip()
        if row["decision"] == "edited" and edited and _norm(edited) != _norm(row["text"]):
            return edited, CLARIFIED
        return row["text"], ORIGINAL

    def _apply_cache(self, uid, ident=None):
        """A reply that is already cached is shown at once (it never runs again). `ident` = (backend kind, model) of the target; default: the active one.
        The cache is shared by both targets (the key has no target in it), so switching does not regenerate. A cached reply keeps the provenance it was made with."""
        text, origin = self.source_text(uid)
        if text is None:
            return False
        backend_name, model = ident or self.engine.identity()[:2]
        key = cache_key(text, backend_name, model)
        hit = self.db.one("SELECT result FROM gen_cache WHERE key=?", (key,))
        if not hit:
            return False
        res = {**loads(hit["result"]), "backend": backend_name, "model": model, "source_text": text, "generated_from": origin}
        res.setdefault("generated_on", DEVICE)  # entries from before the cloud target were all made on this machine
        res.setdefault("endpoint_host", None)
        self._set(uid, "done" if res["status"] == "ok" else "needs_clarification", "from cache", res, res.get("attempts", 1), False, key)
        return True

    def plan(self, pid, policy, only=None):
        """After Part A: show cached replies, then queue what the policy selects (P1, P2, P3 order). `only` = the requirements that are new in this
        analysis (the others are left alone). Returns the number queued."""
        items = []
        ranked = sorted(priority.classes(self.db, pid).items(), key=lambda kv: kv[1])  # stable: document order inside a class
        for uid, cls in ranked:
            if only is not None and uid not in only:
                continue
            existing = self.db.one("SELECT state FROM generation WHERE uid=?", (uid,))
            if existing and existing["state"] in ("queued", "running"):
                continue
            if self._apply_cache(uid):
                continue
            if priority.selected(policy, cls):
                items.append((uid, cls))
        self.enqueue(items)
        return len(items)

    def enqueue_remaining(self, pid):
        """Queue every requirement that has no draft yet ("not generated yet"), best class first. Returns how many."""
        items = []
        ranked = sorted(priority.classes(self.db, pid).items(), key=lambda kv: kv[1])
        for uid, cls in ranked:
            if self.db.one("SELECT 1 x FROM generation WHERE uid=?", (uid,)):
                continue
            if self._apply_cache(uid):
                continue
            items.append((uid, cls))
        self.enqueue(items)
        return len(items)

    def retry_failed(self, pid):
        """Queue again only the drafts of the project that failed (best class first); nothing else is touched. A failed reply is never cached, so each one really
        runs again. The counters of repeated failures start over, so the queue does not skip them at once. Returns how many were queued."""
        items = []
        for uid, cls in sorted(priority.classes(self.db, pid).items(), key=lambda kv: kv[1]):
            row = self.db.one("SELECT state FROM generation WHERE uid=?", (uid,))
            if row and row["state"] == "failed":
                items.append((uid, cls))
        with self._lock:
            self._fails = 0
            self._cloud_fails = 0
        self.enqueue(items)
        return len(items)

    def resume_pending(self):
        """After a restart: everything that was queued or running goes back in the queue with its saved priority. Returns how many."""
        self.db.run("DELETE FROM generation WHERE uid NOT IN (SELECT uid FROM requirements)")
        rows = self.db.all("SELECT uid, priority FROM generation WHERE state IN ('queued','running') ORDER BY priority, updated_at, uid")
        self.enqueue([(r["uid"], r["priority"]) for r in rows])
        return len(rows)

    # ------------------------------------------------------------------------------------------------ pause / timing
    @property
    def paused(self):
        return self._paused.is_set()

    @property
    def paused_reason(self):
        return self._paused_reason if self._paused.is_set() else None

    def set_paused(self, value, reason=None):
        """Pause (optionally with a reason such as "cloud_unreachable") or resume. Resuming forgets the failure counters."""
        if value:
            self._paused_reason = reason
            self._paused.set()
        else:
            self._paused.clear()
            self._paused_reason = None
            self._fails = 0
            self._cloud_fails = 0
        self.db.run("INSERT INTO settings (key, value) VALUES ('gen_paused', ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", ("1" if value else "0",))
        if value and reason:
            self.db.run("INSERT INTO settings (key, value) VALUES ('gen_paused_reason', ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", (reason,))
        else:
            self.db.run("DELETE FROM settings WHERE key='gen_paused_reason'")

    def on_target_changed(self):
        """The user switched target: failure counters start again, an automatic cloud pause ends, and the ETA starts from nothing (it only uses completions after the switch)."""
        self._fails = 0
        self._cloud_fails = 0
        if self._paused.is_set() and self._paused_reason == CLOUD_UNREACHABLE:
            self.set_paused(False)
        with self._cv:
            self._cv.notify_all()

    def eta(self, remaining):
        """(estimated seconds for `remaining` drafts or None, samples). Wall-clock throughput of the last 10 completions of the active target since the last
        switch: n completions between the earliest start and the latest finish. Hidden (None) until 3 completions exist; nothing is made up."""
        backend_name, model, generated_on, _ = self.engine.identity()
        rows = self.db.all(
            "SELECT seconds, finished FROM gen_latency WHERE backend=? AND model=? AND target=? AND finished IS NOT NULL AND finished>=? ORDER BY id DESC LIMIT ?",
            (backend_name, model, generated_on, self.engine.changed_at(), ETA_WINDOW))
        n = len(rows)
        if n < ETA_MIN_SAMPLES or remaining <= 0:
            return None, n
        span = max(r["finished"] for r in rows) - min(r["finished"] - r["seconds"] for r in rows)
        if span <= 0:
            return None, n
        return int(round(remaining / (n / span))), n

    def run_now(self, uid):
        """Regenerate one requirement before everything else in the queue, ignoring the cache."""
        with self._lock:
            self._seq += 1
            ticket = self._seq
            self._ticket[uid] = -ticket  # negative ticket = force
        self._set(uid, "queued")
        self.db.run("UPDATE generation SET priority=0 WHERE uid=?", (uid,))
        self.queue.put((0, ticket, uid, -ticket))

    def sync_draft(self, uid, before_text):
        """The draft follows the effective text (the edited text while the decision is `edited`, else the original). Called after a decision was set or
        removed; `before_text` = the effective text before it. Nothing happens when the text did not change (a comment, accept <-> reject).
        Edited text: a cached reply is shown at once, otherwise the requirement is queued ahead of everything else for the current target, whatever the
        policy. Back to the original: the cached reply, else queued in its priority class; a rejected requirement is never queued. Returns the new state."""
        text, origin = self.source_text(uid)
        if text is None or text == before_text:
            return None
        row = self.db.one("SELECT state, priority FROM generation WHERE uid=?", (uid,))
        if origin == CLARIFIED:
            if not (row and row["state"] in ("queued", "running")) and self._apply_cache(uid):
                return self.db.one("SELECT state FROM generation WHERE uid=?", (uid,))["state"]
            self.run_now(uid)
            return "queued"
        if not row:
            return None  # no draft yet: "Generate draft" will use the original text
        if row["state"] == "queued":
            return "queued"  # it reads the effective text when its turn comes
        if self._apply_cache(uid):
            return self.db.one("SELECT state FROM generation WHERE uid=?", (uid,))["state"]
        if (self.db.one("SELECT decision FROM decisions WHERE uid=?", (uid,)) or {}).get("decision") == "rejected":
            return row["state"]
        self.enqueue([(uid, max(1, row["priority"] or 1))])
        return "queued"

    def request(self, uid):
        """The "Generate draft" / "Regenerate" button. A requirement with no draft yet takes a cached reply if there is one; otherwise (and for any
        existing draft) it is generated now, before everything else in the queue. Returns the resulting state."""
        if not self.db.one("SELECT 1 x FROM generation WHERE uid=?", (uid,)) and self._apply_cache(uid):
            return self.db.one("SELECT state FROM generation WHERE uid=?", (uid,))["state"]
        self.run_now(uid)
        return "queued"

    # ------------------------------------------------------------------------------------------------ dispatcher and pool
    def _release(self):
        with self._cv:
            self._in_flight -= 1
            self._cv.notify_all()

    def _dispatch(self):
        """One thread: admit the next item only while a slot of the ACTIVE target is free, resolve the target for it, then hand it to the pool."""
        while not self._stop.is_set():
            if self._paused.is_set():  # take no NEW item while paused; items already handed over finish
                self._stop.wait(0.2)
                continue
            with self._cv:
                while self._in_flight >= self.engine.concurrency() and not self._stop.is_set() and not self._paused.is_set():
                    self._cv.wait(0.2)
                if self._stop.is_set() or self._paused.is_set():
                    continue
                self._in_flight += 1  # reserved before taking the item, so the limit always holds
            handed = False
            try:
                try:
                    item = self.queue.get(timeout=0.5)
                except queue.Empty:
                    continue
                _, _, uid, ticket = item
                if not uid:  # wake-up marker
                    self.queue.task_done()
                    continue
                if self._paused.is_set():  # paused while this call was waiting: put the item back untouched
                    self.queue.put(item)
                    self.queue.task_done()
                    continue
                try:
                    target = self.engine.resolve()
                except Exception as exc:  # never let the dispatcher die
                    target = Target(DEVICE, self.backend_name, self.model_name, None, error=f"settings could not be read ({exc.__class__.__name__})")
                self._work.put((uid, ticket, target))
                handed = True
            finally:
                if not handed:
                    self._release()

    def _worker(self):
        while True:
            job = self._work.get()
            if job is None:
                return
            uid, ticket, target = job
            try:
                if self._ticket.get(uid) == ticket:
                    self._process(uid, ticket < 0, target)
            except Exception as exc:  # a failure never kills the pool, and the message carries no details that could hold an address or a key
                try:
                    self._set(uid, "failed", f"unexpected error: {exc.__class__.__name__}")
                except Exception:
                    pass
            finally:
                self.queue.task_done()
                self._release()

    def _key_lock(self, key):
        """One lock per cache key: two workers never generate the same key at once."""
        with self._key_guard:
            entry = self._key_locks.setdefault(key, [threading.Lock(), 0])
            entry[1] += 1
        return key, entry[0]

    def _key_unlock(self, key):
        with self._key_guard:
            entry = self._key_locks.get(key)
            if entry:
                entry[1] -= 1
                if entry[1] <= 0:
                    del self._key_locks[key]

    def _process(self, uid, force, target):
        text, origin = self.source_text(uid)  # the user's clarified text when there is one, else the original
        if text is None:
            return
        key = cache_key(text, target.backend_name, target.model)
        _, lock = self._key_lock(key)
        try:
            with lock:
                self._generate(uid, force, target, text, origin, key)
        finally:
            self._key_unlock(key)

    def _generate(self, uid, force, target, text, origin, key):
        if not force and self._apply_cache(uid, (target.backend_name, target.model)):
            return
        if target.error:
            self._set(uid, "failed", f"{ENGINE_UNAVAILABLE}: {target.error}", key=key)
            return
        on_device = target.kind == DEVICE
        if on_device and self.init_error:
            self._set(uid, "failed", self.init_error, key=key)
            return
        if on_device and self._fails >= MAX_FAST_FAILS and not force and target.backend_name == "ollama":
            self._set(uid, "failed", f"{ENGINE_UNAVAILABLE}: skipped after repeated failures; start the model server and press Retry", key=key)
            return
        self._set(uid, "running", key=key)
        started = time.monotonic()
        try:
            result = gen.generate_structured(target.backend, text)
        except ReplayMiss:
            self._set(uid, "failed", NOT_IN_REPLAY, key=key)
            return
        except BackendError as exc:
            if on_device:
                self._fails += 1
                self._set(uid, "failed", f"{ENGINE_UNAVAILABLE}: {exc}", key=key)
            else:
                self._cloud_failed(uid, exc, key)
            return
        if on_device:
            self._fails = 0
        else:
            self._cloud_fails = 0
        elapsed = time.monotonic() - started
        self.db.run("INSERT INTO gen_latency (backend, model, seconds, created_at, target, finished) VALUES (?,?,?,?,?,?)",
                    (target.backend_name, target.model, elapsed, now(), target.kind, time.time()))
        res = {"status": result.status, "user_story": result.user_story, "technical_task": result.technical_task,
               "acceptance_criteria": result.acceptance_criteria, "rationale": result.rationale,
               "clarification_questions": result.clarification_questions, "attempts": result.attempts,
               "manual_review": result.manual_review, "backend": target.backend_name, "model": target.model,
               "generated_on": target.kind, "endpoint_host": target.host,
               "source_text": text, "generated_from": origin,
               "raw_output": result.raw_output if result.manual_review else "",
               "problems": result.problems}
        if result.manual_review:
            self._set(uid, "manual_review", "; ".join(result.problems), res, result.attempts, True, key)
            return
        self.db.run("INSERT OR REPLACE INTO gen_cache (key, result, created_at) VALUES (?,?,?)", (key, dumps(res), now()))
        self._set(uid, "done" if result.status == "ok" else "needs_clarification", "", res, result.attempts, False, key)

    def _cloud_failed(self, uid, exc, key):
        """A cloud connection error, timeout or HTTP error: this item fails (no retry, no fallback to the device); three in a row pause the queue."""
        status = getattr(exc, "status", None)
        if status is not None and 400 <= status < 500:
            message = f"{ENGINE_UNAVAILABLE}: Cloud rejected the request (HTTP {status}); check the key and the model"
        else:
            detail = getattr(exc, "detail", "") or "connection error"
            message = f"{ENGINE_UNAVAILABLE}: Cloud unreachable ({detail})"
        self._set(uid, "failed", message, key=key)
        with self._lock:
            self._cloud_fails += 1
            trip = self._cloud_fails >= CLOUD_FAIL_LIMIT
        if trip and not self._paused.is_set():
            self.set_paused(True, CLOUD_UNREACHABLE)

    # ------------------------------------------------------------------------------------------------ health
    def active_model(self):
        return self.engine.identity()[1]

    def reachable(self):
        """Cheap check for /api/health, for the ACTIVE target. Never raises. The cloud answer is the result of the last connection test (no request per call)."""
        try:
            if self.engine.target() == CLOUD:
                ok, _ = self.engine.tested()
                return bool(ok)
            return self.device_reachable()
        except Exception:
            return False

    def device_reachable(self):
        try:
            if self.init_error:
                return False
            if self.backend_name == "ollama":
                import urllib.request
                s = agent_config.llm_settings()
                with urllib.request.urlopen(s["base_url"] + "/models", timeout=2) as response:
                    listed = [m.get("id", "") for m in json.loads(response.read().decode("utf-8")).get("data", [])]
                wanted = s["model"]
                return bool(wanted) and (wanted in listed or f"{wanted}:latest" in listed)  # the server answers AND serves the configured model
            return True
        except Exception:
            return False
